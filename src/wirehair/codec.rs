#[derive(Clone, Copy, Default)]
struct PeelRow {
    /// Row PRNG seed that generates the set of columns included in this row
    recovery_id: u32,
    /// Linkage in row list
    next_row: u16,
    params: PeelRowParameters,
    /// Count of columns that have not been marked yet
    unmarked_count: u16,
    /// Union: during peeling Unmarked[2]; after peeling Result{PeelColumn:u16, IsCopied:u8}
    /// (IsCopied aliases the low byte of Unmarked[1] in the little-endian C++ layout).
    marks: [u16; 2],
}

impl PeelRow {
    #[inline(always)]
    fn peel_column(&self) -> u16 {
        self.marks[0]
    }
    #[inline(always)]
    fn set_peel_column(&mut self, c: u16) {
        self.marks[0] = c;
    }
    #[inline(always)]
    fn is_copied(&self) -> bool {
        (self.marks[1] & 0xff) != 0
    }
    #[inline(always)]
    fn set_is_copied(&mut self, v: u8) {
        self.marks[1] = (self.marks[1] & 0xff00) | v as u16;
    }
}

