/// Zero-filled vector, or None when the allocator refuses (the C++ calloc failure path).
fn try_zeroed<T: Clone + Default>(n: usize) -> Option<Vec<T>> {
    let mut v = Vec::new();
    v.try_reserve_exact(n).ok()?;
    v.resize(n, T::default());
    Some(v)
}

/// Resize a reused region to `n` elements strictly within its existing capacity; false
/// (nothing changed) when it would have to grow. The C++ reuses one arena whose charged
/// size never shrinks; Rust keeps one Vec per region, so a reuse whose region split
/// differs from the original one must reallocate from scratch instead of growing a
/// region beyond what was charged against the memory limit.
fn reuse_resize<T: Clone + Default>(v: &mut Vec<T>, n: usize) -> bool {
    if n > v.capacity() {
        return false;
    }
    v.resize(n, T::default());
    true
}

