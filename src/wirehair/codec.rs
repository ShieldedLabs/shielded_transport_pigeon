/// Source/input storage. The C++ codec either references the caller's message
/// (encoder, `_input_allocated == 0`) or owns a staging buffer.
#[derive(Clone)]
pub enum InputSource {
    None,
    Owned(Vec<u8>),
    Shared { data: Arc<Vec<u8>>, start: usize, len: usize },
}

impl InputSource {
    #[inline(always)]
    fn bytes(&self) -> &[u8] {
        match self {
            InputSource::None => &[],
            InputSource::Owned(v) => v,
            InputSource::Shared { data, start, len } => &data[*start..*start + *len],
        }
    }
    fn is_none(&self) -> bool {
        matches!(self, InputSource::None)
    }
}

